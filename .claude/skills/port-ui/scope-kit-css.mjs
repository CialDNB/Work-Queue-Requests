#!/usr/bin/env node
// /port-ui kit-baseline isolation: rewrite the kit's global stylesheet into a SCOPED copy for a
// ported app's theme.
//
//   node .claude/skills/port-ui/scope-kit-css.mjs [--in web/src/styles.css] \
//     [--out web/src/theme/kit-scoped.css] [--scope .kit-page] [--check]
//
// Why: the kit's web/src/styles.css styles bare ELEMENTS (button, select, table, th/td, nav, main,
// footer) and generic classes (.app, .card, .topbar, .brand). Loaded globally next to a ported
// source theme, those rules leak into every ported screen - kit-blue buttons, full-width selects, a
// 1180px `.app` that breaks a sidebar layout - and a token bridge can't undo a property the theme
// never sets. So a port does NOT import styles.css. It imports this generated copy, in which:
//
//   1. every selector is prefixed with the scope (`.kit-page button`, `.kit-page .card`), so the
//      kit look applies only inside the kit's own pages (Users, Audit, Tokens, Settings, Login),
//      which the ported shell wraps in <div className="kit-page">;
//   2. every kit custom property is renamed into a `--kit-*` namespace (`var(--radius)` to
//      `var(--kit-radius)`), so it can never collide with - or cycle through - a same-named source
//      token. The theme's bridge then defines the `--kit-*` values from the source tokens;
//   3. `:root`, `html` and `body` rules are dropped: the source theme owns the page (their custom
//      properties stay, as `--kit-*` fallbacks, also when the selector list mixes in a class);
//   4. @media, @supports, @container and @layer blocks are scoped recursively; @keyframes,
//      @font-face and @property are kept with their variables renamed; an `@layer a, b;` order is
//      kept; @charset and @import are dropped. ANY other at-rule stops the script with an error:
//      dropping it silently would leave the kit pages unstyled with --check still green.
//
// styles.css itself stays untouched. It is app-owned, so /kit-upgrade does not carry it: the kit's
// changes to it arrive as CHANGELOG manual steps that apply to it as written. Re-run this script
// after applying one; `--check` fails when the scoped copy is stale (/port-ui Phase 6 and the
// /kit-upgrade verify step run it).
import { existsSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const HEADER =
  '/* GENERATED by .claude/skills/port-ui/scope-kit-css.mjs from web/src/styles.css - do not edit.\n' +
  " * The kit baseline, scoped to the kit's own pages and moved to --kit-* variables (see the\n" +
  ' * script header). Restyle the kit pages through the --kit-* bridge in the theme instead. */\n';

/** `css` without comments; a `/*` inside a string is text, not a comment. */
function stripComments(css) {
  let out = '';
  for (let i = 0; i < css.length; i++) {
    const c = css[i];
    if (c === '"' || c === "'") {
      const end = stringEnd(css, i);
      out += css.slice(i, end);
      i = end - 1;
    } else if (c === '/' && css[i + 1] === '*') {
      const close = css.indexOf('*/', i + 2);
      i = close < 0 ? css.length : close + 1;
    } else out += c;
  }
  return out;
}

/** Index just past the string literal that opens at `i` (backslash escapes honoured). */
function stringEnd(css, i) {
  const quote = css[i];
  let j = i + 1;
  while (j < css.length && css[j] !== quote && css[j] !== '\n') j += css[j] === '\\' ? 2 : 1;
  return Math.min(j + 1, css.length);
}

/**
 * Split CSS into top-level chunks: `{ type: 'rule', selector, body }`, `{ type: 'at', prelude,
 * body }` for a block at-rule, `{ type: 'statement', prelude }` for one that ends in `;`
 * (`@charset`, `@import`, `@layer a, b;`), or `{ type: 'raw', text }` for stray text. Braces and
 * semicolons inside strings are text: `content: "{"` must not open a block.
 */
export function topLevel(css) {
  const out = [];
  const src = stripComments(css);
  let start = 0;
  let i = 0;
  while (i < src.length) {
    const c = src[i];
    if (c === '"' || c === "'") {
      i = stringEnd(src, i);
    } else if (c === ';' && src.slice(start, i).trim().startsWith('@')) {
      out.push({ type: 'statement', prelude: src.slice(start, i).trim() });
      start = i += 1;
    } else if (c === '{') {
      const prelude = src.slice(start, i).trim();
      let depth = 1;
      let j = i + 1;
      while (j < src.length && depth > 0) {
        if (src[j] === '"' || src[j] === "'") {
          j = stringEnd(src, j);
          continue;
        }
        if (src[j] === '{') depth++;
        else if (src[j] === '}') depth--;
        j++;
      }
      const body = src.slice(i + 1, j - 1);
      if (prelude.startsWith('@')) out.push({ type: 'at', prelude, body });
      else out.push({ type: 'rule', selector: prelude, body });
      start = i = j;
    } else i++;
  }
  if (src.slice(start).trim()) out.push({ type: 'raw', text: src.slice(start).trim() });
  return out;
}

/** Split a selector list on TOP-LEVEL commas only (`:is(a, b)` stays one selector). */
export function splitSelectors(list) {
  const parts = [];
  let depth = 0;
  let cur = '';
  for (const ch of list) {
    if (ch === '(' || ch === '[') depth++;
    else if (ch === ')' || ch === ']') depth--;
    if (ch === ',' && depth === 0) {
      parts.push(cur.trim());
      cur = '';
    } else cur += ch;
  }
  if (cur.trim()) parts.push(cur.trim());
  return parts;
}

// A leading page-level compound: `html`, `body`, `:root`, optionally qualified
// (`body.dark`, `html[dir=rtl]`, `:root[data-theme=dark]`).
const PAGE_COMPOUND = /^((?:html|body|:root)(?:[.[:#][^\s>+~]*)?)(?:\s*([>+~])?\s*)(.*)$/;

/**
 * Scope one selector. `X` becomes `.kit-page X`; a page-level compound stays in front so its
 * condition still applies (`body.dark .card` becomes `body.dark .kit-page .card`). A selector that
 * is ONLY a page-level compound returns null: it styles the page, which the source theme owns.
 */
export function scopeOne(selector, scope) {
  const m = selector.match(PAGE_COMPOUND);
  if (!m) return selector === '*' ? `${scope} *` : `${scope} ${selector}`;
  const [, compound, , rest] = m;
  return rest ? `${compound} ${scope} ${rest}` : null;
}

/** `.kit-page X` for each selector in a list (null when nothing scoped is left). */
export function scopeSelector(selectorList, scope) {
  const scoped = splitSelectors(selectorList)
    .map((s) => scopeOne(s, scope))
    .filter(Boolean);
  return scoped.length ? scoped.join(',\n') : null;
}

/** Rename every custom property declaration and reference into the --kit-* namespace. */
export function namespaceVars(text) {
  return text.replace(/--(?!kit-)([a-zA-Z][\w-]*)/g, '--kit-$1');
}

/** A selector that is ONLY a page-level compound (`:root`, `html`, `body.dark`), no descendant. */
const isPageOnly = (p) => PAGE_COMPOUND.test(p) && !p.match(PAGE_COMPOUND)[3];

/**
 * The custom properties of the page-level-only selectors in a rule (`:root`, `html`,
 * `:root[data-theme=dark]`), namespaced, as a token rule, or null. A plain `:root`/`html` becomes
 * `:where(:root)`, a zero-specificity FALLBACK the theme's bridge (loaded later) overrides; a
 * qualified one keeps its qualifier so a theme/direction switch still applies. Non-token
 * declarations are dropped: the source theme owns the page.
 */
function tokenRule(pageParts, body) {
  if (!pageParts.length) return null;
  const decls = [...body.matchAll(/(--[\w-]+)\s*:\s*([^;]+);?/g)].map(
    ([, name, value]) => `  ${namespaceVars(name)}: ${namespaceVars(value.trim())};`,
  );
  if (!decls.length) return null;
  const selector = [
    ...new Set(pageParts.map((p) => (p === ':root' || p === 'html' ? ':where(:root)' : p))),
  ].join(',\n');
  return `${selector} {\n${decls.join('\n')}\n}`;
}

/**
 * One rule, scoped. A mixed list (`:root, .dark { --bg: #000 }`) keeps BOTH halves: the page-level
 * selectors become a token rule and the rest is scoped. Dropping the list as a whole lost the
 * :root tokens.
 */
function scopedRule(selector, body, scope, indent = '') {
  const parts = splitSelectors(selector);
  const pageParts = parts.filter(isPageOnly);
  const out = [];
  const token = tokenRule(pageParts, body);
  if (token) out.push(token);
  const scoped = scopeSelector(parts.filter((p) => !isPageOnly(p)).join(', '), scope);
  if (scoped) out.push(`${scoped} {${namespaceVars(body).replace(/\s+$/, '')}\n}`);
  return out.map((block) => block.replace(/^(?=.)/gm, indent)).join('\n');
}

/** At-rules whose body is more rules: scoped recursively, prelude kept. */
const GROUPING = /^@(media|supports|container|layer)\b/i;
/** At-rules carried over as they are, with kit variables renamed. */
const VERBATIM = /^@(-webkit-)?(keyframes|font-face|property)\b/i;
/**
 * Statements deliberately not carried: @charset (the bundle is UTF-8 anyway), @import (a remote
 * or ordering-sensitive sheet the port does not load). An `@layer a, b;` order statement is kept.
 */
const DROPPED_STATEMENT = /^@(charset|import)\b/i;

function scopeChunks(chunks, scope, indent) {
  const blocks = [];
  for (const chunk of chunks) {
    if (chunk.type === 'rule') {
      const rule = scopedRule(chunk.selector, chunk.body, scope, indent);
      if (rule) blocks.push(rule);
    } else if (chunk.type === 'at' && GROUPING.test(chunk.prelude)) {
      const inner = scopeChunks(topLevel(chunk.body), scope, `${indent}  `);
      if (inner.length) blocks.push(`${indent}${chunk.prelude} {\n${inner.join('\n')}\n${indent}}`);
    } else if (chunk.type === 'at' && VERBATIM.test(chunk.prelude)) {
      blocks.push(`${indent}${namespaceVars(chunk.prelude)} {${namespaceVars(chunk.body)}}`);
    } else if (chunk.type === 'statement' && /^@layer\b/i.test(chunk.prelude)) {
      blocks.push(`${indent}${chunk.prelude};`);
    } else if (chunk.type === 'statement' && DROPPED_STATEMENT.test(chunk.prelude)) {
      // deliberately not carried over (see DROPPED_STATEMENT)
    } else if (chunk.type === 'raw') {
      // stray text outside any rule: nothing to scope
    } else {
      // Silently dropping it would leave the kit pages unstyled with --check green.
      const name = (chunk.prelude ?? '').match(/^@[\w-]+/)?.[0] ?? chunk.prelude;
      throw new Error(`unhandled at-rule ${name}: extend scope-kit-css.mjs to scope it`);
    }
  }
  return blocks;
}

export function scopeKitCss(css, scope = '.kit-page') {
  return `${HEADER}\n${scopeChunks(topLevel(css), scope, '').join('\n\n')}\n`;
}

function arg(argv, name, fallback) {
  const i = argv.indexOf(`--${name}`);
  return i >= 0 && argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[i + 1] : fallback;
}

export function run(argv) {
  const input = arg(argv, 'in', 'web/src/styles.css');
  const output = arg(argv, 'out', 'web/src/theme/kit-scoped.css');
  const scope = arg(argv, 'scope', '.kit-page');
  if (!existsSync(input)) return { code: 1, err: `${input}: not found` };
  const next = scopeKitCss(readFileSync(input, 'utf8'), scope);
  if (argv.includes('--check')) {
    const have = existsSync(output) ? readFileSync(output, 'utf8') : '';
    return have === next
      ? { code: 0, out: `${output} is current ✓` }
      : {
          code: 1,
          err: `${output} is stale - re-run: node ${fileURLToPath(import.meta.url)}`,
        };
  }
  writeFileSync(output, next);
  return { code: 0, out: `wrote ${output} (scope ${scope})` };
}

function isMain() {
  try {
    return realpathSync(fileURLToPath(import.meta.url)) === realpathSync(process.argv[1] ?? '');
  } catch {
    return false;
  }
}

if (isMain()) {
  const { code, out, err } = run(process.argv.slice(2));
  if (out) console.log(out);
  if (err) console.error(err);
  process.exit(code);
}
